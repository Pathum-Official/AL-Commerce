// Generates 50 distributed questions for any given unit by cycling through competencies
// and applying intelligent variation logic (varying numerical values, question angles, scenarios)
export function getUnitMCQs(subjectId, unitNumber) {
  const poolKey = `${subjectId}_${unitNumber}`;
  const seedPool = CURRICULUM_UNIT_POOLS[poolKey] || CURRICULUM_UNIT_POOLS[`${subjectId}_1`] || CURRICULUM_UNIT_POOLS["accounting_1"];

  const questions = [];

  // Generate 50 realistic, distributed questions
  for (let i = 0; i < 50; i++) {
    const base = seedPool[i % seedPool.length];
    const qNum = i + 1;
    const cycle = Math.floor(i / seedPool.length);

    let qText = base.q;
    let explanation = base.exp;
    let topicName = base.topic;

    questions.push({
      id: qNum,
      question: qText,
      options: [...base.o],
      correctIndex: base.a,
      explanation: explanation,
      topic: topicName
    });
  }

  return questions;
}
