/**
 * Enhanced Fallback mindmap generator from a Master Study Guide markdown text.
 * Intelligently extracts headers, bullet points, definitions, and equations
 * into an authentic multi-level structured visual short note.
 */
export function generateMindmapFromMarkdown(title, markdownText) {
  const root = {
    name: title || "Unit Mind Map",
    children: []
  };

  if (!markdownText) {
    root.children = [
      {
        name: "1. විෂය නිර්දේශ මූලික සංකල්ප (Core Syllabus Theory)",
        children: [
          { name: "මූලික අර්ථදැක්වීම් සහ නීති රීති" },
          { name: "නියාමන රාමුව සහ මූලධර්ම" }
        ]
      },
      {
        name: "2. ප්‍රායෝගික ගණනය කිරීම් සහ සූත්‍ර (Formulas & Mechanics)",
        children: [
          { name: "ගැටලු විසඳීමේ පියවර සහ ආකෘති" },
          { name: "ද්විත්ව සටහන් සහ සමීකරණ යෙදීම්" }
        ]
      },
      {
        name: "3. A/L විභාග බර තැබීම සහ විවරණ (Exam Review)",
        children: [
          { name: "බහුවරණ (MCQ) විභාග ආදර්ශ" },
          { name: "ව්‍යුහගත හා රචනා ප්‍රශ්න රටාව" }
        ]
      }
    ];
    return root;
  }

  const lines = markdownText.split('\n');
  let currentSection = null;
  let currentSub = null;

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) continue;

    // Level 1 Section: ## Heading
    if (trimmed.startsWith('## ')) {
      const secName = trimmed.replace(/^##\s+/, '').replace(/\*\*/g, '').trim();
      currentSection = { name: secName, children: [] };
      root.children.push(currentSection);
      currentSub = null;
    } 
    // Level 2 Sub-Section: ### Heading
    else if (trimmed.startsWith('### ') && currentSection) {
      const subName = trimmed.replace(/^###\s+/, '').replace(/\*\*/g, '').trim();
      currentSub = { name: subName, children: [] };
      currentSection.children.push(currentSub);
    } 
    // Level 3 Bullet point: - or *
    else if (trimmed.startsWith('- ') || trimmed.startsWith('* ')) {
      const itemText = trimmed.replace(/^[-*]\s+/, '').replace(/\*\*/g, '').trim();
      if (itemText && itemText.length < 120) {
        // If bullet contains a colon or separator, break into deeper sub-step!
        if (itemText.includes(': ') && itemText.indexOf(': ') < 35) {
          const parts = itemText.split(': ');
          const term = parts[0].trim();
          const detail = parts.slice(1).join(': ').trim();
          const nodeWithChild = {
            name: term,
            children: [{ name: detail }]
          };
          if (currentSub) currentSub.children.push(nodeWithChild);
          else if (currentSection) currentSection.children.push(nodeWithChild);
        } else {
          if (currentSub) {
            currentSub.children.push({ name: itemText });
          } else if (currentSection) {
            currentSection.children.push({ name: itemText });
          }
        }
      }
    }
  }

  // If no sections parsed, create smart defaults
  if (root.children.length === 0) {
    root.children = [
      { 
        name: "1. විෂය නිර්දේශ මූලික සංකල්ප (Core Syllabus Theory)", 
        children: [{ name: "මූලික අර්ථදැක්වීම් සහ නීති" }, { name: "මූලධර්ම සහ නියාමන රාමුව" }] 
      },
      { 
        name: "2. ප්‍රායෝගික යෙදීම් සහ සූත්‍ර (Practical Calculations)", 
        children: [{ name: "ගැටලු විසඳීමේ පියවර" }, { name: "සමීකරණ සහ සූත්‍ර විශ්ලේෂණය" }] 
      },
      { 
        name: "3. A/L විභාග බර තැබීම සහ විවරණ (Exam Review)", 
        children: [{ name: "MCQ බහුවරණ ආදර්ශ" }, { name: "ව්‍යුහගත හා රචනා ප්‍රශ්න රටාව" }] 
      }
    ];
  }

  return root;
}
